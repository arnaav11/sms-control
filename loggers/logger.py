import logging

class Logger:
    def __init__(self):
        self.FORMAT: str
        self.logger: logging.Logger

    def info(self, msg: str) -> None:
        self.logger.info(msg)

    def warning(self, msg: str) -> None:
        self.logger.warning(msg)

    def error(self, msg: str) -> None:
        self.logger.error(msg)

    